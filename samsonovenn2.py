def cifar_resnet(depth, num_classes=10, bn_momentum=0.05, zero_init_last_bn=False):
    n = (depth - 2) // 6
    norm = partial(nn.BatchNorm2d, momentum=bn_momentum)
    layers = [conv3x3(3, 16), norm(16), nn.ReLU(inplace=True)]
    c_in = 16
    for c_out in (16, 32, 64):
        for _ in range(n):
            stride = 1 if c_in == c_out else 2
            shortcut = None if stride == 1 else nn.Sequential(
                nn.AvgPool2d(2), nn.ZeroPad3d((0, 0, 0, 0, 0, c_out - c_in))
            )
            layers.append(BasicBlock(c_in, c_out, stride, shortcut, norm_layer=norm))
            c_in = c_out
    layers += [nn.AdaptiveAvgPool2d(1), nn.Flatten(), nn.Linear(64, num_classes)]
    model = nn.Sequential(*layers)

    for m in model.modules():
        if isinstance(m, nn.Conv2d):
            nn.init.kaiming_normal_(m.weight, mode="fan_out", nonlinearity="relu")
        if zero_init_last_bn and isinstance(m, BasicBlock):
            nn.init.zeros_(m.bn2.weight)
    return model

def lenet(num_classes=10):
    model = nn.Sequential(
        nn.Conv2d(1, 20, 5), nn.MaxPool2d(2), nn.Conv2d(20, 50, 5), nn.MaxPool2d(2), nn.Flatten(),
        nn.Linear(800, 500), nn.ReLU(), nn.Linear(500, num_classes),
    )

    for m in model:
        if isinstance(m, (nn.Conv2d, nn.Linear)):
            a = math.sqrt(3.0 / m.weight[0].numel())
            nn.init.uniform_(m.weight, -a, a)
            nn.init.zeros_(m.bias)
    return model

def sgd(model, lr=0.1, momentum=0.9, wd=1e-4):
    return torch.optim.SGD(
        [dict(params=[p for p in model.parameters() if p.ndim > 1], weight_decay=wd),
         dict(params=[p for p in model.parameters() if p.ndim <= 1], weight_decay=0.0)],
        lr=lr, momentum=momentum,
    )

