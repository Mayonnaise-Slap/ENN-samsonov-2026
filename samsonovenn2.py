def make_loader(ds, bs, train, seed=0):
    sampler = RandomSampler(ds, generator=torch.Generator()) if train else None
    return DataLoader(
        ds, batch_size=bs, sampler=sampler, drop_last=train, num_workers=os.cpu_count(), pin_memory=True,
        persistent_workers=True, generator=torch.Generator().manual_seed(seed),
    )

def batches(loader, seed, start_it=0):
    shuffle = getattr(loader.sampler, "sampler", loader.sampler)
    epoch, skip = divmod(start_it, len(loader))
    while True:
        shuffle.generator.manual_seed(seed * 100_003 + epoch)
        for i, (x, y) in enumerate(loader):
            if i >= skip:
                yield (x.to(device, non_blocking=True, memory_format=torch.channels_last),
                       y.to(device, non_blocking=True))
        epoch, skip = epoch + 1, 0

# had issues with LR ramping too fast with one cycle shcedule

def smooth_ramp(x):
    x = min(max(x, 0.0), 1.0)
    return x * x / (x * x + (1 - x) ** 2)

