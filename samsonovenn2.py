def run_name(cfg, keys=("model", "depth", "n_train", "sched", "lr_hi", "lr0", "wd", "bs", "iters", "seed")):
    return cfg["exp"] + "/" + "_".join(f"{k}{cfg[k]}" for k in keys if k in cfg)

@torch.no_grad()
def evaluate(model, loader, train_mode=False):
    was_training = model.training
    if train_mode:
        model = copy.deepcopy(model)
    model.train(train_mode)
    loss_sum = torch.zeros((), device=device)
    correct = torch.zeros((), device=device)
    for x, y in loader:
        x = x.to(device, non_blocking=True, memory_format=torch.channels_last)
        y = y.to(device, non_blocking=True)
        logits = model(x).float()
        loss_sum += F.cross_entropy(logits, y, reduction="sum")
        correct += (logits.argmax(1) == y).sum()
    model.train(was_training)
    n = len(loader.dataset)
    return loss_sum.item() / n, correct.item() / n

def train(name, cfg, model, opt, sched, train_loader, eval_loader, final_loader, hooks=(), stop_at=None, root=ROOT):
    """Train for cfg["iters"] iterations with AMP and return the result dict.

    stop_at: checkpoint and return None at the first eval at or after this iteration (session budget).
    """
    res_path = root / "results" / f"{name}.json"
    ckpt_path = root / "checkpoints" / f"{name}.pt"
    if res_path.exists():
        print(f"[{name}] already done, loading the result")
        return json.loads(res_path.read_text())
    res_path.parent.mkdir(parents=True, exist_ok=True)
    ckpt_path.parent.mkdir(parents=True, exist_ok=True)

    total = cfg["iters"]
    scaler = torch.amp.GradScaler("cuda")
    losses = torch.full((total,), float("nan"), device=device)
    state = dict(it=0, history=[], flags=[], t_train=0.0, t_eval=0.0)
    stateful = dict(model=model, opt=opt, sched=sched, scaler=scaler) | {f"hook{i}": h for i, h in enumerate(hooks)}
    if ckpt_path.exists():
        ck = torch.load(ckpt_path, map_location=device, weights_only=False)
        for key, obj in stateful.items():
            obj.load_state_dict(ck[key])
        state = ck["state"]
        losses[:state["it"]] = ck["losses"]
        print(f"[{name}] resumed at it {state['it']}")

    win = torch.zeros(3, device=device)
    status = "complete"
    model.train()
    data = batches(train_loader, cfg["seed"], state["it"])
    t0 = time.perf_counter()
    for it in range(state["it"], total):
        x, y = next(data)
        lr = opt.param_groups[0]["lr"]
        mom = opt.param_groups[0]["momentum"]

        with torch.autocast("cuda", dtype=torch.float16):
            logits = model(x)
            loss = F.cross_entropy(logits, y)
        opt.zero_grad(set_to_none=True)
        scale_before = scaler.get_scale() if hooks else None
        scaler.scale(loss).backward()
        scaler.step(opt)
        scaler.update()
        sched.step()

        loss = loss.detach().float()
        losses[it] = loss
        win += torch.stack([loss.nan_to_num(0.0, 0.0, 0.0), loss.isfinite().float(),
                           (logits.argmax(1) == y).sum().float()])
        for h in hooks:
            h(it, model, lr, scaler.get_scale() >= scale_before)

        if (it + 1) % cfg["eval_every"] and it + 1 < total:
            continue

        # eval
        torch.cuda.synchronize()
        t1 = time.perf_counter()
        state["t_train"] += t1 - t0
        loss_sum, finite_steps, correct = win.tolist()
        win.zero_()
        steps = it + 1 - (state["history"][-1]["it"] if state["history"] else 0)
        row = dict(
            it=it + 1, lr=lr, momentum=mom, train_loss=loss_sum / max(finite_steps, 1),
            train_acc=correct / (steps * len(y)), nonfinite=steps - int(finite_steps),
        )
        row["test_loss"], row["test_acc"] = evaluate(model, eval_loader)
        if cfg.get("log_train_mode"):
            row["test_acc_trainmode"] = evaluate(model, eval_loader, train_mode=True)[1]
        state["t_eval"] += time.perf_counter() - t1
        row["t_train"], row["t_eval"] = state["t_train"], state["t_eval"]
        state["history"].append(row)
        print(f"[{name}] " + " ".join(f"{k} {v:.4g}" for k, v in row.items()))

        # collapse
        if abs(row["train_loss"] - math.log(cfg["n_classes"])) < 0.05 and row["train_acc"] < 1.5 / cfg["n_classes"]:
            state["flags"].append(f"collapsed@{it + 1}")
        # divirged
        weights = torch.cat([t.flatten() for t in model.state_dict().values() if t.is_floating_point()])
        if not weights.isfinite().all() or row["nonfinite"] > steps / 2:
            status = "diverged"
            state["flags"].append(f"diverged@{it + 1}")
            break

        state["it"] = it + 1
        if (it + 1) % cfg["ckpt_every"] == 0 or (stop_at is not None and it + 1 >= stop_at):
            torch.save({k: obj.state_dict() for k, obj in stateful.items()} | dict(state=state, losses=losses[:it + 1]),
                       ckpt_path)
        if stop_at is not None and it + 1 >= stop_at and it + 1 < total:
            print(f"[{name}] stopped at it {it + 1}, rerun to resume")
            return None
        t0 = time.perf_counter()

    final_loss, final_acc = evaluate(model, final_loader)
    accs = [r["test_acc"] for r in state["history"]]
    result = dict(
        name=name, cfg=cfg, env=env, status=status, flags=state["flags"], history=state["history"],
        final=dict(
            test_loss=final_loss, test_acc=final_acc, best_eval_acc=max(accs),
            mean_last3_eval_acc=float(np.mean(accs[-3:])), t_train=state["t_train"], t_eval=state["t_eval"],
        ),
        hooks=[h.state_dict() for h in hooks],
    )
    np.save(root / "results" / f"{name}.losses.npy", losses.cpu().numpy())
    res_path.write_text(json.dumps(result, indent=1))
    ckpt_path.unlink(missing_ok=True)
    print(f"[{name}] {status}: final test acc {final_acc:.4f}, flags {state['flags']}")
    return result

