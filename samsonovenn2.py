def random_crop_flip(x, pad=4):
    b, _, h, w = x.shape
    theta = torch.zeros(b, 2, 3, device=x.device)
    theta[:, 0, 0] = torch.randint(0, 2, (b,), device=x.device) * 2 - 1
    theta[:, 1, 1] = 1

    theta[:, :, 2] = torch.randint(-pad, pad + 1, (b, 2), device=x.device) * 2 / torch.tensor([w, h], device=x.device)
    grid = F.affine_grid(theta, list(x.shape), align_corners=False)
    return F.grid_sample(x, grid, mode="nearest", padding_mode="zeros", align_corners=False)


