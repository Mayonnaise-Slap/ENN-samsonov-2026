from collections import deque

def one_cycle_v2(opt, total, lr_min, lr_max, cycle_frac=0.9, final_div=100.0, m_min=0.85, m_max=0.95,
                 max_slope=MAX_SAFE_LR_SLOPE, min_warmup=100):
    sched = OneCycleLR(
        opt, max_lr=lr_max, total_steps=total, pct_start=cycle_frac / 2, anneal_strategy="linear",
        div_factor=lr_max / lr_min, final_div_factor=final_div, three_phase=True,
        base_momentum=m_min, max_momentum=m_max,
    )
    slope = (lr_max - lr_min) / (cycle_frac * total / 2)
    if slope <= max_slope:
        return sched
    warmup = max(min_warmup, math.ceil(2 * lr_min / max_slope))
    warnings.warn(
        f"1cycle ramp {lr_min} -> {lr_max} over {int(cycle_frac * total / 2)} its is {slope:.2e} lr/it "
        f"(safe: {max_slope:.0e}); adding a {warmup}-it smooth warm-up"
    )
    ramp = MultiplicativeLR(opt, lambda it: smooth_ramp(it / warmup))
    for g in opt.param_groups:
        g["lr"] *= smooth_ramp(0)
    return ChainedScheduler([sched, ramp])

class LrEstimatorV2:
    # second version, after experiment: the denominator from the real gradients
    def __init__(self, source="weights", stride=1, every=1, first=None, alpha=0.1):
        assert source in ("weights", "grads")
        self.source, self.stride, self.every, self.first, self.alpha = source, stride, every, first, alpha
        self.points = deque(maxlen=2 * stride + 1)
        self.pending = None
        self.trace = []
        self.ema = None

    def __call__(self, it, model, lr, step_ok):
        if self.first is not None and it > self.first + 2 * self.stride + 1:
            return
        if not step_ok:
            self.points.clear()
            self.pending = None
            return
        params = list(model.parameters())
        if self.pending is not None:

            grad = torch.cat([p.grad.detach().reshape(-1) for p in params]) if self.source == "grads" else None
            self.points.append((it, self.pending, grad, lr))
        self.pending = torch.cat([p.detach().reshape(-1) for p in params])
        if len(self.points) < self.points.maxlen:
            return

        (k, wa, ga, lra), (_, wb, gb, _), (_, wc, _, _) = self.points[0], self.points[self.stride], self.points[-1]
        if k % self.every or (self.first is not None and k >= self.first):
            return
        if self.source == "grads":
            est = ((wb - wa).abs().sum() / (gb - ga).abs().sum()).item()
        else:
            est = (lra * (wb - wa).abs().sum() / (2 * wb - wa - wc).abs().sum()).item()
        self.ema = est if self.ema is None else self.alpha * est + (1 - self.alpha) * self.ema
        self.trace.append((k, est, self.ema))

    def state_dict(self):
        return dict(trace=self.trace, ema=self.ema)

    def load_state_dict(self, state):
        self.trace, self.ema = state["trace"], state["ema"]
        self.points.clear()
        self.pending = None

