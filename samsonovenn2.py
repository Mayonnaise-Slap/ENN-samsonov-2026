def one_cycle(opt, total, lr_min, lr_max, cycle_frac=0.9, final_div=100.0, m_min=0.85, m_max=0.95,
              max_slope=MAX_SAFE_LR_SLOPE, min_warmup=100):
    sched = OneCycleLR(
        opt, max_lr=lr_max, total_steps=total, pct_start=cycle_frac / 2, anneal_strategy="linear",
        div_factor=lr_max / lr_min, final_div_factor=final_div, three_phase=True,
        base_momentum=m_min, max_momentum=m_max,
    )
    slope = (lr_max - lr_min) / (cycle_frac * total / 2)
    if slope <= max_slope:
        return sched
    warmup = max(min_warmup, math.ceil(2 * lr_min / max_slope))
    warnings.warn(
        f"1cycle ramp {lr_min} -> {lr_max} over {int(cycle_frac * total / 2)} its is {slope:.2e} lr/it "
        f"(safe: {max_slope:.0e}); adding a {warmup}-it smooth warm-up"
    )

    return ChainedScheduler([sched, MultiplicativeLR(opt, lambda it: smooth_ramp(it / warmup))])

def piecewise_constant(opt, total, lr0, milestones=(0.5, 0.75), gamma=0.1, warmup=0):

    for g in opt.param_groups:
        g["lr"] = lr0
    steps = [int(m * total) for m in milestones]
    if not warmup:
        return MultiStepLR(opt, steps, gamma)
    return SequentialLR(
        opt, [LinearLR(opt, start_factor=1 / warmup, total_iters=warmup),
              MultiStepLR(opt, [s - warmup for s in steps], gamma)],
        milestones=[warmup],
    )

class LrEstimator:
    # The paper's hessian-free LR estimator
    def __init__(self, mode="every", first=300, every=10, alpha=0.1):
        assert mode in ("every", "sparse")
        self.mode, self.first, self.every, self.alpha = mode, first, every, alpha
        self.buf = []
        self.trace = []
        self.ema = None

    def _wanted(self, j):
        if self.mode == "every":
            return j <= self.first + 2
        return j >= self.every and j % self.every < 3

    def __call__(self, it, model, lr, step_ok):
        j = it + 1
        if not step_ok:
            self.buf.clear()
            return
        if not self._wanted(j):
            return
        if self.buf and self.buf[-1][0] != j - 1:
            self.buf.clear()

        self.buf.append((j, torch.cat([p.detach().reshape(-1) for p in model.parameters()]), lr))
        if len(self.buf) < 3:
            return
        (i, w0, _), (_, w1, lr0), (_, w2, lr1) = self.buf
        d1, d2 = w1 - w0, w2 - w1
        est = (d1.abs().sum() / (d1 / lr0 - d2 / lr1).abs().sum()).item()
        self.ema = est if self.ema is None else self.alpha * est + (1 - self.alpha) * self.ema
        self.trace.append((i, est, self.ema))
        if self.mode == "every":
            self.buf.pop(0)
        else:
            self.buf.clear()

    def state_dict(self):
        return dict(trace=self.trace, ema=self.ema)

    def load_state_dict(self, state):
        self.trace, self.ema, self.buf = state["trace"], state["ema"], []

