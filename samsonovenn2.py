def schedule_trace(build, total):
    opt = torch.optim.SGD([torch.zeros(1, requires_grad=True)], lr=1.0, momentum=0.9)
    sched = build(opt)
    lrs, moms = [], []
    for _ in range(total):
        lrs.append(opt.param_groups[0]["lr"])
        moms.append(opt.param_groups[0]["momentum"])
        opt.step()
        sched.step()
    return np.array(lrs), np.array(moms)

